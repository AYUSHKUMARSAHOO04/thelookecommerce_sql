-- q40: What percentage of customers acquired in each month made another purchase within 30 days.
with first_order as (
select user_id, min(date(created_at)) as first_order_date
from `bigquery-public-data.thelook_ecommerce.orders`
group by user_id),
customer_orders as (
select f.user_id, f.first_order_date, date_trunc(f.first_order_date, month) as acquired_month, date(o.created_at) as order_date
from first_order f
  join `bigquery-public-data.thelook_ecommerce.orders` o
  on f.user_id = o.user_id)
select format_date('%B %Y', acquired_month) as acquired_months, count(distinct user_id) as customers_acquired, format_date('%B %Y', date_add(acquired_month, interval 1 month)) as next_month, count(distinct case when date_diff(order_date, first_order_date, day) between 1 and 30 then user_id end) as retention_nxt30_days, round(safe_divide(count(distinct case when date_diff(order_date, first_order_date, day) between 1 and 30 then user_id end) * 100, count(distinct user_id)), 2) as retention_rate
from customer_orders
group by acquired_month
order by acquired_month;

-- q41: What is the average number of days between purchases for repeat customers.
with customer_orders as (
select user_id, date(created_at) as order_date, lag(date(created_at)) over(
partition by user_id
order by created_at) as previous_order_date
from `bigquery-public-data.thelook_ecommerce.orders`)
select round(avg(date_diff(order_date, previous_order_date, day)), 2) as avg_days_between_orders
from customer_orders
where previous_order_date is not null;

